// Helper to create past date relative to today
const getPastDate = (daysAgo: number, hour = 11, minute = 30): string => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

